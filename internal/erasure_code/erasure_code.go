package erasure_code

import (
	"errors"
	"fmt"
	"math/big"

	"github.com/consensys/gnark-crypto/ecc/bls12-381/fr"
	"github.com/crate-crypto/go-eth-kzg/internal/domain"
	"github.com/crate-crypto/go-eth-kzg/internal/poly"
)

// BlockErasureIndex is used to indicate the index of the block erasure that is missing
// from the codeword.
type BlockErasureIndex = uint64

// DataRecovery implements a unique decoding algorithm.
//
// The algorithm is not generic and is specific to the use-case where:
//   - We have block erasures. ie we do not lose data in random locations, but in contiguous chunks.
//     The chunks themselves are predetermined.
type DataRecovery struct {
	// rootsOfUnityBlockErasureIndex is a domain that corresponds to the number of blocks
	// that we can have in the codeword.
	rootsOfUnityBlockErasureIndex *domain.Domain
	domainExtended                *domain.Domain
	// dataWordCoset evaluates polynomials on a coset of a domain the size of the data
	// word. The quotient we ultimately want has degree < numScalarsInDataWord, so the
	// coset round-trip does not need the full codeword-sized domain.
	dataWordCoset *domain.CosetDomain
	// vanishingCoset evaluates the compressed vanishing polynomial on the image of
	// dataWordCoset under x -> x^blockErasureSize. That image has only
	// numScalarsInDataWord/blockErasureSize distinct points, so this domain is small.
	vanishingCoset *domain.CosetDomain
	// foldPowers[j] is cosetGen^(numScalarsInDataWord*j) for j in [0, expansionFactor).
	//
	// Every point x of dataWordCoset satisfies x^numScalarsInDataWord == foldPowers[1],
	// and every point y of vanishingCoset satisfies y^(numScalarsInDataWord/blockErasureSize)
	// == foldPowers[1] as well. Folding a polynomial's coefficients by these powers
	// therefore leaves its values on those cosets unchanged.
	foldPowers []fr.Element
	// blockErasureSize indicates the size of `blocks of evaluations` that
	// can be missing. For example, if blockErasureSize is 4, then 4 evaluations
	// can be missing, or 8 or 16.
	//
	// This is contrary to a general unique decoding algorithm where the number of
	// missing elements can be any number and the evaluations do not need to
	// be in blocks.
	blockErasureSize int
	// numScalarsInCodeword is the number of scalars in the codeword
	// ie the number of scalars we get when we get encode the data.
	numScalarsInCodeword int
	// numScalarsInDataWord is the number of scalars in the message
	// that we encode.
	numScalarsInDataWord int
	// expansionFactor is the factor by which the data word or message is expanded
	expansionFactor int
	// totalNumBlocks is the total number of blocks(groups of evaluations) in the codeword
	totalNumBlocks int
}

func NewDataRecovery(blockErasureSize, numScalarsInDataWord, expansionFactor int) *DataRecovery {
	// The recovery algorithm relies on Z(x) = Zhat(x^blockErasureSize), which only holds
	// when the blocks tile the data word exactly. Without this check the integer
	// divisions below silently round, every derived domain still comes out a power of two
	// so nothing panics, and recovery returns a wrong polynomial rather than an error.
	if blockErasureSize <= 0 || expansionFactor <= 0 {
		panic("blockErasureSize and expansionFactor must be positive")
	}
	if numScalarsInDataWord%blockErasureSize != 0 {
		panic("blockErasureSize must divide numScalarsInDataWord")
	}

	// Compute the number of scalars that will be in the codeword
	numScalarsInCodeword := numScalarsInDataWord * expansionFactor

	// Compute the total number of blocks that we will need to
	// represent the codeword
	totalNumBlocks := numScalarsInCodeword / blockErasureSize

	rootsOfUnityBlockErasureIndex := domain.NewDomain(uint64(totalNumBlocks))
	domainExtended := domain.NewDomain(uint64(numScalarsInCodeword))

	cosetGen := fr.NewElement(7)
	var invCosetGen fr.Element
	invCosetGen.Inverse(&cosetGen)
	dataWordCoset := domain.NewCosetDomain(
		domain.NewDomain(uint64(numScalarsInDataWord)),
		domain.FFTCoset{CosetGen: cosetGen, InvCosetGen: invCosetGen},
	)

	// The vanishing polynomial is evaluated on the coset generated by cosetGen^blockErasureSize,
	// which is where dataWordCoset lands under x -> x^blockErasureSize.
	var vanishingCosetGen, invVanishingCosetGen fr.Element
	vanishingCosetGen.Exp(cosetGen, big.NewInt(int64(blockErasureSize)))
	invVanishingCosetGen.Inverse(&vanishingCosetGen)
	vanishingCoset := domain.NewCosetDomain(
		domain.NewDomain(uint64(numScalarsInDataWord/blockErasureSize)),
		domain.FFTCoset{CosetGen: vanishingCosetGen, InvCosetGen: invVanishingCosetGen},
	)

	foldPowers := make([]fr.Element, expansionFactor)
	foldPowers[0] = fr.One()
	if expansionFactor > 1 {
		foldPowers[1].Exp(cosetGen, big.NewInt(int64(numScalarsInDataWord)))
		for j := 2; j < expansionFactor; j++ {
			foldPowers[j].Mul(&foldPowers[j-1], &foldPowers[1])
		}
	}

	return &DataRecovery{
		rootsOfUnityBlockErasureIndex: rootsOfUnityBlockErasureIndex,
		domainExtended:                domainExtended,
		dataWordCoset:                 dataWordCoset,
		vanishingCoset:                vanishingCoset,
		foldPowers:                    foldPowers,
		blockErasureSize:              blockErasureSize,
		numScalarsInCodeword:          numScalarsInCodeword,
		numScalarsInDataWord:          numScalarsInDataWord,
		expansionFactor:               expansionFactor,
		totalNumBlocks:                totalNumBlocks,
	}
}

// Encode the polynomial by evaluating it on the extended domain.
//
// Note: `polyCoeff` is mutated in-place, ie it should be seen as mutable reference.
func (dr *DataRecovery) Encode(polyCoeff []fr.Element) []fr.Element {
	// Pad to the correct length
	for i := len(polyCoeff); i < len(dr.domainExtended.Roots); i++ {
		polyCoeff = append(polyCoeff, fr.Element{})
	}
	dr.domainExtended.FftFr(polyCoeff)
	return polyCoeff
}

// NumBlocksNeededToReconstruct returns the number of blocks that are needed to reconstruct
// the original data word.
func (dr *DataRecovery) NumBlocksNeededToReconstruct() int {
	return dr.numScalarsInDataWord / dr.blockErasureSize
}

// RecoverPolynomialCoefficients recovers the coefficients of the data word polynomial P
// from a codeword with block erasures.
//
// The algorithm is the standard vanishing-polynomial ("zero polynomial") argument: with
// Z the polynomial vanishing on the missing evaluation points, (E*Z) and (P*Z) agree
// everywhere, so P can be recovered by dividing (P*Z) by Z on a coset where Z has no
// roots. Two properties of the block-erasure setting keep the transforms small:
//
//   - Z is not evaluated at codeword size. The vanishing polynomial is
//     Z(x) = Zhat(x^blockErasureSize), so its evaluations over the codeword domain repeat
//     with period totalNumBlocks, and over dataWordCoset with period
//     numScalarsInDataWord/blockErasureSize. Both are far smaller than the codeword, so
//     Z only ever needs those small transforms.
//   - The quotient is not computed at codeword size. P has degree < numScalarsInDataWord,
//     so the coset round-trip is done on a domain of that size after folding (P*Z) down
//     to numScalarsInDataWord coefficients, which is exact on the coset.
//
// This leaves one codeword-sized transform (the inverse FFT of (E*Z)) and two data-word
// sized ones, rather than five codeword-sized transforms.
func (dr *DataRecovery) RecoverPolynomialCoefficients(data []fr.Element, missingIndices []BlockErasureIndex) ([]fr.Element, error) {
	if len(data) != dr.numScalarsInCodeword {
		return nil, errors.New("length of data should equal the number of scalars in the codeword")
	}

	// More erasures than the code can correct would not fail loudly below: the compressed
	// vanishing polynomial would be silently truncated to totalNumBlocks coefficients, or
	// the folding would index past foldPowers.
	if maxMissing := dr.totalNumBlocks - dr.NumBlocksNeededToReconstruct(); len(missingIndices) > maxMissing {
		return nil, fmt.Errorf("cannot recover from %d missing blocks: at most %d of the %d blocks may be missing",
			len(missingIndices), maxMissing, dr.totalNumBlocks)
	}

	zHat := dr.compressedVanishingPoly(missingIndices)

	// Z's evaluations over the codeword domain, of which there are only totalNumBlocks
	// distinct values: Z(w^i) = Zhat(w^(blockErasureSize*i)) and w^blockErasureSize has
	// order totalNumBlocks.
	zEval := make([]fr.Element, dr.totalNumBlocks)
	copy(zEval, zHat)
	dr.rootsOfUnityBlockErasureIndex.FftFr(zEval)

	// (E*Z) in evaluation form. Z is zero exactly on the missing positions, so the
	// erased entries of `data` never contribute and (E*Z) == (P*Z) pointwise.
	blockMask := dr.totalNumBlocks - 1
	eZEval := make([]fr.Element, len(data))
	for i := range data {
		z := &zEval[i&blockMask]
		if z.IsZero() {
			continue
		}
		eZEval[i].Mul(&data[i], z)
	}

	dr.domainExtended.IfftFr(eZEval)
	dzPoly := eZEval

	// Fold (P*Z) to numScalarsInDataWord coefficients and move to the coset, where Z has
	// no roots and the division is well defined.
	cosetQuotientEval := dr.foldToDataWord(dzPoly)
	dr.dataWordCoset.CosetFFtFr(cosetQuotientEval)

	invZOnCoset := dr.invVanishingPolyOnDataWordCoset(zHat)
	vanishingMask := len(invZOnCoset) - 1
	for i := range cosetQuotientEval {
		cosetQuotientEval[i].Mul(&cosetQuotientEval[i], &invZOnCoset[i&vanishingMask])
	}

	dr.dataWordCoset.CosetIFFtFr(cosetQuotientEval)

	return cosetQuotientEval, nil
}

// compressedVanishingPoly returns Zhat, the polynomial whose roots are the block-erasure
// roots of unity of the missing indices.
//
// The vanishing polynomial over the codeword domain is Z(x) = Zhat(x^blockErasureSize):
// spreading Zhat's coefficients at stride blockErasureSize gives Z, so Zhat carries all
// of Z's information in totalNumBlocks/expansionFactor times fewer coefficients.
//
// Note: These blockErasure indices should not be in bit reversed order
func (dr *DataRecovery) compressedVanishingPoly(missingBlockErasureIndices []BlockErasureIndex) []fr.Element {
	missingBlockErasureIndexRoots := make([]fr.Element, len(missingBlockErasureIndices))
	for i, index := range missingBlockErasureIndices {
		missingBlockErasureIndexRoots[i] = dr.rootsOfUnityBlockErasureIndex.Roots[index]
	}

	return vanishingPolyCoeff(missingBlockErasureIndexRoots)
}

// foldToDataWord reduces a codeword-sized polynomial to numScalarsInDataWord coefficients
// without changing its values on dataWordCoset. Every point x of that coset satisfies
// x^numScalarsInDataWord == foldPowers[1], so coefficient i+j*numScalarsInDataWord can be
// added into coefficient i scaled by foldPowers[j].
func (dr *DataRecovery) foldToDataWord(coeffs []fr.Element) []fr.Element {
	numScalars := dr.numScalarsInDataWord

	folded := make([]fr.Element, numScalars)
	copy(folded, coeffs[:numScalars])

	for j := 1; j < dr.expansionFactor; j++ {
		chunk := coeffs[j*numScalars : (j+1)*numScalars]
		for i := range chunk {
			var scaled fr.Element
			scaled.Mul(&chunk[i], &dr.foldPowers[j])
			folded[i].Add(&folded[i], &scaled)
		}
	}

	return folded
}

// invVanishingPolyOnDataWordCoset returns the inverses of Z evaluated on dataWordCoset.
//
// Z(x) = Zhat(x^blockErasureSize) maps dataWordCoset onto vanishingCoset, which has only
// numScalarsInDataWord/blockErasureSize points, so this is a small transform followed by
// a small batch inversion. Z has no roots on the coset, so every value is invertible.
func (dr *DataRecovery) invVanishingPolyOnDataWordCoset(zHat []fr.Element) []fr.Element {
	numDistinct := dr.numScalarsInDataWord / dr.blockErasureSize

	// Fold Zhat down to numDistinct coefficients. Every point y of vanishingCoset
	// satisfies y^numDistinct == foldPowers[1], by the same argument as foldToDataWord.
	folded := make([]fr.Element, numDistinct)
	for i := range zHat {
		var scaled fr.Element
		scaled.Mul(&zHat[i], &dr.foldPowers[i/numDistinct])
		folded[i%numDistinct].Add(&folded[i%numDistinct], &scaled)
	}

	dr.vanishingCoset.CosetFFtFr(folded)

	return fr.BatchInvert(folded)
}

// vanishingPolyCoeff returns the polynomial that has roots at the given points
func vanishingPolyCoeff(xs []fr.Element) poly.PolynomialCoeff {
	result := []fr.Element{fr.One()}

	for _, x := range xs {
		// This is to silence: G601: Implicit memory aliasing in for loop.
		x := x

		negX := fr.Element{}
		negX.Neg(&x)
		result = poly.PolyMul(result, []fr.Element{negX, fr.One()})
	}

	return result
}
